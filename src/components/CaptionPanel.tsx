import { ProgressValue, ProgressLabel, Progress } from "@/components/ui/progress";
import { Spinner } from "@/components/ui/spinner";
import { Button } from "@/components/ui/button";

type CaptionPanelProps = {
  error: string;
  progress: number;
  ready: boolean;
  caption: string
  workerFailed: boolean;
  restartWorker: () => void;
}

export function CaptionPanel({ error, progress, ready, caption, workerFailed, restartWorker }: CaptionPanelProps) {
  return (<>
    {(!error && progress > 0) && (!ready &&
      <Progress value={progress} className='w-full'>
        <ProgressLabel>Loading model</ProgressLabel>
        <ProgressValue />
      </Progress>
    )}
    <div className='text-start'>{
      error
      || (caption && (
        <section>
          <p>{caption}</p>
          <p className='mt-1 italic text-muted-foreground'>This description was generated by the model and may contain errors.</p>
        </section>
      ))
      || (ready && (
        <div className="flex items-center gap-2">
          <Spinner />
          <span>Analyzing image...</span>
        </div>))
    }</div>
    {workerFailed && (
      <Button type="button" onClick={restartWorker}>
        Restart Worker
      </Button>
    )}
  </>);
}
